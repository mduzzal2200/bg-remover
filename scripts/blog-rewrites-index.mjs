#!/usr/bin/env node
/**
 * Writes src/app/blog/_data/rewrites/index.ts from the rewrite files next to
 * it (one per post slug). Run after adding a rewrite: npm run blog:rewrites
 */
import fs from "node:fs";
import path from "node:path";

const DIR = "src/app/blog/_data/rewrites";
const files = fs.readdirSync(DIR).filter((f) => f.endsWith(".ts") && !["index.ts", "types.ts"].includes(f)).sort();
const ident = (slug) => "r_" + slug.replace(/[^a-z0-9]+/gi, "_");
const out = `// Generated by scripts/blog-rewrites-index.mjs — do not edit by hand.
import type { BlogPost } from "../posts";
import type { BlogRewrite } from "./types";
${files.map((f) => `import ${ident(f.slice(0, -3))} from "./${f.slice(0, -3)}";`).join("\n")}

/** Rewritten posts by slug (see types.ts). */
export const REWRITES: Record<string, BlogRewrite> = {
${files.map((f) => `  "${f.slice(0, -3)}": ${ident(f.slice(0, -3))},`).join("\n")}
};

/** The post with its rewrite applied: new copy in place, or extra sections before its FAQ. */
export function withRewrite<T extends BlogPost>(post: T): T {
  const r = REWRITES[post.slug];
  if (!r) return post;
  const { sections, append, ...fields } = r;
  let next = sections ?? post.sections;
  if (append?.length) {
    const at = next.findIndex((s) => /frequently asked questions|faqs?\\b/i.test(s.heading || ""));
    next = at < 0 ? [...next, ...append] : [...next.slice(0, at), ...append, ...next.slice(at)];
  }
  return { ...post, ...fields, sections: next };
}
`;
fs.writeFileSync(path.join(DIR, "index.ts"), out);
console.log(`Wrote ${files.length} rewrites to ${DIR}/index.ts`);
